/**
 * The course map: every chapter, every planned lesson, and every lesson's learning objectives,
 * written or not.
 *
 * The course follows the Hebrew University syllabus of 77101 "מכניקה ויחסות פרטית" (7 credits,
 * read from the catalogue on 2026-11-06, kept in .claude/specs/huji-77101.json): mathematical
 * introduction, Newton's laws, conservation laws, collisions, the harmonic oscillator, the two-body
 * problem and Kepler's laws, non-inertial frames, the rigid body, and kinematics and dynamics in
 * special relativity. Each chapter names the syllabus item it covers in `syllabus`.
 *
 * Objectives live here, not only in the lesson front matter, so that the question banks (the
 * comprehension ladder of each lesson and the review problems of each chapter) can be written and
 * practised before the lesson text exists. A written lesson declares exactly the objectives listed
 * here (lint-content enforces it). Written lessons live in src/content/lessons as MDX; the lessons
 * collection is the only list of what is written, this list is the order and the promise.
 *
 * Objective texts are plain text (lesson header, My Path, test report): no TeX. A formula in one
 * is wrapped in U+2066 … U+2069 with no-break spaces inside.
 */

export interface Objective {
  id: string;
  text: string;
}

export interface PlannedLesson {
  id: string;
  title: string;
  objectives: Objective[];
  /** the topic's place in 77101 is unverified: marked on the contents page until /exam-map settles it */
  enrichment?: boolean;
}

export interface Chapter {
  n: number;
  title: string;
  /** one line under the chapter title on the contents page */
  blurb: string;
  /** the 77101 syllabus item(s) the chapter covers, as the catalogue words them */
  syllabus: string;
  lessons: PlannedLesson[];
}

/** Build a lesson's objective list from its texts: OBJ-<lesson>-1, -2, … */
const lesson = (id: string, title: string, texts: string[], enrichment = false): PlannedLesson => ({
  id,
  title,
  objectives: texts.map((text, i) => ({ id: `OBJ-${id}-${i + 1}`, text })),
  ...(enrichment ? { enrichment } : {}),
});

